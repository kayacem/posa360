#!/usr/bin/env bash
# Issue Let's Encrypt certs for verified merchant custom domains + write nginx vhosts.
# Root cron every 5 min. Never reloads nginx without a successful nginx -t.
# Does not modify unrelated server blocks — only writes under posa-eticaret-custom/.
set -euo pipefail

APP_ENV="${APP_ENV:-/opt/posa/apps/eticaret/.env}"
API_BASE="${API_BASE:-https://eticaret.posa360.com}"
NGINX_CUSTOM_DIR="${NGINX_CUSTOM_DIR:-/etc/nginx/sites-available/posa-eticaret-custom}"
NGINX_ENABLED_DIR="${NGINX_ENABLED_DIR:-/etc/nginx/sites-enabled}"
EMAIL="${ACME_EMAIL:-admin@posa360.com}"

if [[ -f "$APP_ENV" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "$APP_ENV"
  set +a
fi

SECRET="${CERT_AGENT_SECRET:-}"
if [[ -z "$SECRET" ]]; then
  echo "CERT_AGENT_SECRET missing" >&2
  exit 1
fi

mkdir -p "$NGINX_CUSTOM_DIR"

json="$(curl -fsS -H "X-Cert-Agent-Secret: ${SECRET}" "${API_BASE}/api/internal/pending-certs")"
mapfile -t domains < <(printf '%s' "$json" | python3 -c 'import json,sys
for d in json.load(sys.stdin).get("domains", []):
    print(d["domain"])')

if [[ ${#domains[@]} -eq 0 ]]; then
  echo "No pending certs."
  exit 0
fi

mark_status() {
  local domain="$1" status="$2" message="${3:-}"
  local payload
  payload="$(python3 -c 'import json,sys; print(json.dumps({"domain":sys.argv[1],"status":sys.argv[2],"message":sys.argv[3]}))' "$domain" "$status" "$message")"
  curl -fsS -X POST \
    -H "X-Cert-Agent-Secret: ${SECRET}" \
    -H "Content-Type: application/json" \
    -d "$payload" \
    "${API_BASE}/api/internal/pending-certs" >/dev/null || true
}

write_vhost() {
  local domain="$1"
  local conf="${NGINX_CUSTOM_DIR}/${domain}.conf"
  cat >"$conf" <<EOF
# Auto-generated by issue-domain-cert.sh — do not edit by hand
server {
    listen 80;
    listen [::]:80;
    server_name ${domain} www.${domain} admin.${domain};
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${domain} www.${domain};
    ssl_certificate     /etc/letsencrypt/live/${domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 32m;
    location / {
        proxy_pass http://posa_eticaret;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name admin.${domain};
    ssl_certificate     /etc/letsencrypt/live/${domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 32m;
    location / {
        proxy_pass http://posa_eticaret;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
  ln -sfn "$conf" "${NGINX_ENABLED_DIR}/posa-eticaret-${domain}.conf"
}

safe_reload_nginx() {
  if nginx -t; then
    systemctl reload nginx
    echo "nginx reloaded"
  else
    echo "nginx -t FAILED — not reloading (other server blocks untouched)" >&2
    return 1
  fi
}

for domain in "${domains[@]}"; do
  [[ -z "$domain" ]] && continue
  echo "==> Cert for ${domain} + www + admin.${domain}"
  if certbot certonly --nginx --non-interactive --agree-tos -m "$EMAIL" \
      -d "$domain" -d "www.${domain}" -d "admin.${domain}"; then
    write_vhost "$domain"
    if safe_reload_nginx; then
      mark_status "$domain" issued
    else
      mark_status "$domain" failed "nginx -t failed after cert"
    fi
  else
    mark_status "$domain" failed "certbot failed"
  fi
done
