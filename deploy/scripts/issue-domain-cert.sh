#!/usr/bin/env bash
# Issue Let's Encrypt certs via HTTP-01 (certbot --nginx) for:
#   - platform store hosts: {slug}.posa360.com
#   - verified custom domains: domain + admin.domain
# Writes per-host nginx includes; never reloads without nginx -t.
# Until a host has a cert, HTTP-only catch-all / pending vhost serves it (no HTTPS redirect).
set -euo pipefail

APP_ENV="${APP_ENV:-/opt/posa/apps/eticaret/.env}"
API_BASE="${API_BASE:-https://eticaret.posa360.com}"
NGINX_HOSTS_DIR="${NGINX_HOSTS_DIR:-/etc/nginx/sites-available/posa-eticaret-hosts}"
EMAIL="${ACME_EMAIL:-admin@posa360.com}"

if [[ -f "$APP_ENV" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "$APP_ENV"
  set +a
fi

SECRET="${CERT_AGENT_SECRET:-}"
if [[ -z "$SECRET" ]]; then
  echo "CERT_AGENT_SECRET missing" >&2
  exit 1
fi

mkdir -p "$NGINX_HOSTS_DIR"
touch "${NGINX_HOSTS_DIR}/.keep.conf"

json="$(curl -fsS -H "X-Cert-Agent-Secret: ${SECRET}" "${API_BASE}/api/internal/pending-certs")"

mark_status() {
  local kind="$1" host="$2" status="$3" tenant_id="${4:-}" message="${5:-}"
  local payload
  payload="$(python3 -c 'import json,sys; print(json.dumps({"kind":sys.argv[1],"host":sys.argv[2],"status":sys.argv[3],"tenantId":sys.argv[4],"message":sys.argv[5]}))' \
    "$kind" "$host" "$status" "$tenant_id" "$message")"
  curl -fsS -X POST \
    -H "X-Cert-Agent-Secret: ${SECRET}" \
    -H "Content-Type: application/json" \
    -d "$payload" \
    "${API_BASE}/api/internal/pending-certs" >/dev/null || true
}

safe_reload_nginx() {
  if nginx -t; then
    systemctl reload nginx
    echo "nginx reloaded"
    return 0
  fi
  echo "nginx -t FAILED — not reloading (other server blocks untouched)" >&2
  return 1
}

write_https_vhost() {
  local primary="$1"
  shift
  local names="$primary"
  local e
  for e in "$@"; do
    names="${names} ${e}"
  done

  local conf="${NGINX_HOSTS_DIR}/${primary}.conf"
  local live="/etc/letsencrypt/live/${primary}"

  cat >"$conf" <<EOF
# Auto-generated by issue-domain-cert.sh — do not edit by hand
server {
    listen 80;
    listen [::]:80;
    server_name ${names};
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${names};
    ssl_certificate     ${live}/fullchain.pem;
    ssl_certificate_key ${live}/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
    client_max_body_size 32m;
    location / {
        proxy_pass http://posa_eticaret;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
}

write_http_only_custom() {
  local domain="$1"
  local conf="${NGINX_HOSTS_DIR}/${domain}.http-pending.conf"
  cat >"$conf" <<EOF
# Temporary HTTP-only vhost until cert is issued — issue-domain-cert.sh
server {
    listen 80;
    listen [::]:80;
    server_name ${domain} www.${domain} admin.${domain};
    location /.well-known/acme-challenge/ { root /var/www/html; }
    client_max_body_size 32m;
    location / {
        proxy_pass http://posa_eticaret;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
}

printf '%s' "$json" | python3 -c '
import json,sys
data=json.load(sys.stdin)
for item in data.get("hosts") or data.get("domains") or []:
    kind=item.get("kind","custom")
    host=item.get("host") or ""
    tenant=item.get("tenantId") or ""
    hosts=",".join(item.get("hosts") or [host])
    print(f"{kind}\t{host}\t{tenant}\t{hosts}")
' > /tmp/posa-pending-hosts.tsv

if [[ ! -s /tmp/posa-pending-hosts.tsv ]]; then
  echo "No pending certs."
  exit 0
fi

while IFS=$'\t' read -r kind host tenant_id hosts_csv; do
  [[ -z "$host" ]] && continue
  echo "==> kind=${kind} host=${host} hosts=${hosts_csv}"

  IFS=',' read -r -a host_list <<< "$hosts_csv"

  if [[ "$kind" == "custom" ]]; then
    write_http_only_custom "$host"
    if ! safe_reload_nginx; then
      mark_status custom "$host" failed "$tenant_id" "nginx -t failed before cert"
      continue
    fi
  fi

  certbot_args=(certonly --nginx --non-interactive --agree-tos -m "$EMAIL" --cert-name "$host")
  for h in "${host_list[@]}"; do
    [[ -n "$h" ]] && certbot_args+=(-d "$h")
  done

  if certbot "${certbot_args[@]}"; then
    rm -f "${NGINX_HOSTS_DIR}/${host}.http-pending.conf"
    if [[ "$kind" == "custom" ]]; then
      write_https_vhost "$host" "www.${host}" "admin.${host}"
    else
      write_https_vhost "$host"
    fi
    if safe_reload_nginx; then
      mark_status "$kind" "$host" issued "$tenant_id"
    else
      mark_status "$kind" "$host" failed "$tenant_id" "nginx -t failed after cert"
    fi
  else
    mark_status "$kind" "$host" failed "$tenant_id" "certbot failed"
  fi
done < /tmp/posa-pending-hosts.tsv
